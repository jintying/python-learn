"""
第 02 课 · 为什么需要函数
================================================================
这一课不讲语法，只讲「为什么」。
看完你就会明白：函数不是发明出来折磨人的，是被逼出来的。
"""

print("=" * 64)
print("第 02 课 · 为什么需要函数")
print("=" * 64)

print("""
需求：算「接管率」。
公式：接管次数 ÷ 总里程 × 1000
（意思是：每 1000 公里要接管几次，数字越小说明车越稳）
""")


# ==================================================================
# 第一幕：没有函数的时候，有多难受
# ==================================================================
print("=" * 64)
print("第一幕：没有函数，只能复制粘贴")
print("=" * 64)

print("\n--- 第 1 天的数据 ---")
jieguan = 3
licheng = 100
print(f"接管率：{jieguan / licheng * 1000} 次/千公里")

print("\n--- 第 2 天的数据 ---")
jieguan = 1
licheng = 200
print(f"接管率：{jieguan / licheng * 1000} 次/千公里")

print("\n--- 第 3 天的数据 ---")
jieguan = 5
licheng = 250
print(f"接管率：{jieguan / licheng * 1000} 次/千公里")

print("""
看出问题了吗？
    算一次，就要把「÷ 总里程 × 1000」写一遍。
    换一组数据，就得把整段代码再抄一遍。
""")


# ==================================================================
# 第二幕：真正的麻烦 —— 公式要改
# ==================================================================
print("=" * 64)
print("第二幕：如果公式要改呢？")
print("=" * 64)

print("""
领导说：以后不按 1000 公里算，改成按 100 公里算。
也就是要把每一处的  * 1000  改成  * 100 。

这里只有 3 个地方要改，还好。
但如果这个脚本用了 30 次呢？你要改 30 个地方。
漏掉一个，那个数字就是错的 —— 而且你根本发现不了。

这不是"会不会写代码"的问题，这是"人一定会犯错"的问题。
""")


# ==================================================================
# 第三幕：函数登场
# ==================================================================
print("=" * 64)
print("第三幕：用函数，改一处，全都跟着变")
print("=" * 64)


def 算接管率(jieguan, licheng):
    """接管次数 ÷ 总里程 × 1000"""
    return jieguan / licheng * 1000


print("\n--- 第 1 天 ---")
print(f"接管率：{算接管率(3, 100)} 次/千公里")

print("\n--- 第 2 天 ---")
print(f"接管率：{算接管率(1, 200)} 次/千公里")

print("\n--- 第 3 天 ---")
print(f"接管率：{算接管率(5, 250)} 次/千公里")

print("""
对比一下：

    没有函数：算一次，抄一遍代码。公式改了要改 30 处。
    有函数：  公式只写一次，以后「喊名字」。公式改了只改 1 处。

函数 = 给一段代码起个名字。
以后你只要喊这个名字，那段代码就会帮你跑一遍。
""")

print("=" * 64)
print("刚才那个「算接管率」就是个真正的函数，我们再喊它几次：")
print("=" * 64)

for j, l in [(0, 500), (2, 1000), (7, 3000)]:
    print(f"    {j} 次接管 / {l} 公里  ->  {算接管率(j, l)} 次每千公里")

print("""
注意最后这几行：同一个函数，喂不同的数字，出不同的结果。
这就叫「复用」——写一次，用无数次。

下一课我们正式开始拆解函数怎么写。
""")
