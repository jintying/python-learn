"""
第 05 课 · return：函数把结果交出来
================================================================
这是最重要的一课。

如果你前面都学得似懂非懂，那这一课学会，函数就通了。

核心只有一句话：

        print 是「喊出来」—— 屏幕上看得见，但外面拿不到
        return 是「交出来」—— 外面能接住，可以继续用
"""

print("=" * 64)
print("第 05 课 · return（最重要的一课）")
print("=" * 64)


# ==================================================================
# 第一步：先看一个「坑」
# ==================================================================
print("\n【第一步】先看一个很多人踩过的坑")

print("""
下面这个函数，用 print 把结果显示出来。
看起来好像没问题，我们试试把它接到一个变量里。
""")


def 算接管率_错误示范(jieguan, licheng):
    print(f"    计算结果是：{jieguan / licheng * 1000}")


print("\n调用它：")
jieguo = 算接管率_错误示范(3, 100)

print(f"\n我在外面接到的「结果」是：{jieguo}")
print("    ↑ 为什么是 None ？？？")

print("""
None 的意思是「什么都没有」。

原因：
    print 只是把文字「喊」到屏幕上给人看。
    它喊完就完了，没有把任何东西交给外面。

所以你用 jieguo = 函数() 去接，接到的是空气 —— 也就是 None。
""")


# ==================================================================
# 第二步：改用 return
# ==================================================================
print("=" * 64)
print("【第二步】改用 return，就拿到了")
print("=" * 64)


def 算接管率(jieguan, licheng):
    return jieguan / licheng * 1000      # 注意这里是 return，不是 print


print("\n调用它：")
jieguo = 算接管率(3, 100)
print(f"\n我在外面接到的结果是：{jieguo}")
print("    ↑ 这次拿到了！")

print("""
区别就在这一个词：

    print  -> 屏幕上显示，函数外面【拿不到】  -> 只能给人看
    return -> 交给外面，函数外面【能接住】    -> 程序可以继续用
""")


# ==================================================================
# 第三步：拿到了能干嘛？—— 能继续算
# ==================================================================
print("=" * 64)
print("【第三步】拿到结果之后，能继续做事情")
print("=" * 64)

print("""
因为 return 把值交出来了，所以外面可以拿它继续计算。
如果只有 print，这一步就做不到。
""")

# 拿到结果之后继续计算
r1 = 算接管率(3, 100)
r2 = 算接管率(1, 200)
r3 = 算接管率(5, 250)

print(f"    第 1 天：{r1} 次/千公里")
print(f"    第 2 天：{r2} 次/千公里")
print(f"    第 3 天：{r3} 次/千公里")

平均 = (r1 + r2 + r3) / 3
print(f"    三天平均：{平均} 次/千公里")

if 平均 > 10:
    print("    结论：接管偏多，需要关注")
else:
    print("    结论：表现正常")

print("""
看到了吗？r1、r2、r3 都是数字，所以能相加、能求平均、能比较。
如果函数里用的是 print，r1 就是 None，None + None 会直接报错。
""")


# ==================================================================
# 第四步：这就是自动化测试的起点
# ==================================================================
print("=" * 64)
print("【第四步】这就是自动化测试的起点")
print("=" * 64)

print("""
有了 return，我们就能「自动判断结果对不对」。

assert 这个词的意思是「断言」：我认定它是这样，如果不是就报错。
""")


def 算接管率2(jieguan, licheng):
    return jieguan / licheng * 1000


print("\n来做一次自动判断：")
assert 算接管率2(3, 100) == 30.0
print("    ✅ 断言通过：3 次接管 / 100 公里 确实是 30.0")

assert 算接管率2(1, 200) == 5.0
print("    ✅ 断言通过：1 次接管 / 200 公里 确实是 5.0")

print("""
这段 assert，就是「自动化测试」最小的样子。

    机器自己算出一个结果，
    自己拿去和标准答案比，
    一样就通过，不一样就报错。

你在 pytest 里看到的所有测试，本质上都是这个。
但前提是：函数必须用 return 把结果交出来，
否则测试拿不到值，就没办法比。

这就是为什么我上次要把你原来的 log_analyzer.py 重构成用 return 的版本。
""")


# ==================================================================
# 第五步：关于 return 的三条规矩
# ==================================================================
print("=" * 64)
print("【第五步】return 的三条规矩")
print("=" * 64)

print("""
规矩 1：没有 return 的函数，默认返回 None
        这就是第一步那个坑的根本原因。

规矩 2：return 后面的代码不会执行（函数到那就结束了）
""")

def 演示():
    print("    我要 return 了")
    return 1
    print("    这行永远不会执行")      # 这行是死的


演示()

print("""
规矩 3：return 可以写在 if 里面 —— 于是同一个函数能返回不同结果
""")

def 判通过(error数, 上限):
    if error数 > 上限:
        return False          # 太多，不通过
    return True               # 否则通过


print(f"    ERROR=5，上限=10  ->  {判通过(5, 10)}")
print(f"    ERROR=15，上限=10 ->  {判通过(15, 10)}")

print("""
看到没？一个函数，两条 return，根据情况走不同的路。
这是真实代码里最常见的写法。

下一课我们两样合起来用：用 if + return 写一个真正的「判断函数」。
""")


