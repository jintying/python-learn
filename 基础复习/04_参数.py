"""
第 04 课 · 参数：给函数递材料
================================================================
上一课的「打招呼」每次说的话都一样。
可是如果我想跟不同的人打招呼呢？总不能写 10 个函数吧。

参数就是解决这个的：函数括号里写的名字，就是它需要的「材料」。
"""

print("=" * 64)
print("第 04 课 · 参数")
print("=" * 64)


# ==================================================================
# 第一步：把会变的东西，变成参数
# ==================================================================
print("\n【第一步】把「会变的东西」变成参数")

# 没有参数：只能说同一句话
print("\n没有参数，只能说同一句：\n")


def 打招呼_固定():
    print("    你好，余泽泓")


打招呼_固定()
打招呼_固定()      # 还是同一句

# 有参数：括号里写一个名字，就代表"这里要填东西"
print("\n有参数，每次可以不一样：\n")


def 打招呼(名字):
    print(f"    你好，{名字}")


打招呼("余泽泓")
打招呼("面试官")
打招呼("小鹏的 HR")

print("""
看出来了吗？
    括号里的「名字」是个占位符，你调用时填什么，它就变成什么。

    定义的时候：括号里写「我需要什么材料」
    调用的时候：括号里填「这次用的是什么材料」
""")


# ==================================================================
# 第二步：多个参数，按顺序填
# ==================================================================
print("=" * 64)
print("【第二步】多个参数：按顺序对应")
print("=" * 64)


def 算接管率(jieguan, licheng):
    """接管次数 ÷ 总里程 × 1000"""
    jieguo = jieguan / licheng * 1000
    print(f"    {jieguan} 次接管 / {licheng} 公里  =  {jieguo} 次每千公里")


print("\n按顺序填进去：")
算接管率(3, 100)      # 3 给了 jieguan，100 给了 licheng
算接管率(1, 200)
算接管率(7, 3000)

print("""
注意：是【按位置】对应的。
    第 1 个值 -> 第 1 个参数
    第 2 个值 -> 第 2 个参数
要是填反了，结果就完全错了，而且程序不会报错 —— 这是很危险的事。
""")


# ==================================================================
# 第三步：最关键的一点 —— 参数和外面的变量没关系
# ==================================================================
print("=" * 64)
print("【第三步】最容易搞混的一点：参数只是「位置上的名字」")
print("=" * 64)

print("""
外面叫 a、b，函数里叫 jieguan、licheng，名字完全不一样，但照样能传。
因为传递的是【值】，不是名字本身。
""")

a = 3
b = 100
print(f"用外面的变量当材料：算接管率(a, b)")
算接管率(a, b)

print("""
再把这件事推到底：函数里面改了参数，外面会不会变？
我们做个实验。
""")


def 改一下(x):
    print(f"    刚进函数时，x = {x}")
    x = 999
    print(f"    我把它改成了 x = {x}")


n = 5
print(f"调用前，外面的 n = {n}")
改一下(n)
print(f"调用完，外面的 n = {n}   <-- 居然没变！")

print("""
为什么？因为：
    函数里的 x 和外面的 n 是【两个不同的盒子】。
    调用的时候，是把 n 里的值「抄一份」放进 x 这个盒子。
    所以你在函数里怎么折腾 x，都动不到外面的 n。

这个规则叫「传值」。记住结论就够了：
    函数内部的参数变量，和外面的变量，是两个独立的东西。
""")


# ==================================================================
# 第四步：默认参数（可选材料）
# ==================================================================
print("=" * 64)
print("【第四步】默认参数：给材料一个默认值")
print("=" * 64)


def 算接管率2(jieguan, licheng, 系数=1000):
    """系数不填的话，默认按 1000 公里算"""
    jieguo = jieguan / licheng * 系数
    print(f"    系数={系数}  结果={jieguo}")


print("\n不填第三个参数，就用默认的 1000：")
算接管率2(3, 100)

print("\n填了第三个参数，就按你填的来：")
算接管率2(3, 100, 100)      # 按 100 公里算

print("""
默认参数的写法就是： 参数名=默认值
好处是：常用的情况下少写一点，特殊情况下又能自己指定。
（注意：带默认值的参数必须放在最后面）
""")


