# 一、报错长什么样
# ==================================================================
print("""
【一】报错的样子

假设你写了一个文件，里面有一处名字打错了，运行后屏幕上会出现这样一段：

    Traceback (most recent call last):
      File "D:\\test.py", line 3, in <module>
        print(jieguo)
              ^^^^^^
    NameError: name 'jieguo' is not defined

别被吓到，它只有三个部分，而且【从下往上读最快】：
""")

print("""
    ① 最后一行  NameError: name 'jieguo' is not defined
       -> 这是「什么错」。翻译：jieguo 这个名字没有定义过。
       这一行永远是最重要的，先看它。

    ② 倒数第二段  File "...", line 3
       -> 这是「错在哪」。翻译：test.py 的第 3 行。
       注意：如果中间有很多行 File，只有【最后一个 File】才是真正出错的地方。

    ③ 最上面那行 Traceback (most recent call last):
       -> 这个是固定格式，意思是"下面是从最早到最后的调用过程"。
       新手可以直接忽略它。
""")

print("""
所以正确的读法是：
        先看最后一行（什么错） -> 再看最后那个 File 行（哪一行） -> 去改
""")


# ==================================================================
# 二、你会遇到的 6 种报错
# ==================================================================
print("=" * 64)
print("【二】新手必遇到的 6 种报错")
print("=" * 64)

# --- 1. NameError ---
print("\n① NameError —— 用了一个不存在的名字（最常见）")
print("   原因：名字打错了 / 忘了先定义 / 大小写不一致")
try:
    print(没有定义过的变量)
except NameError as e:
    print(f"   实际报错：{e}")

# --- 2. SyntaxError ---
print("\n② SyntaxError —— 语法写错了")
print("   原因：最常见的是 if / for / def 那一行末尾漏了冒号 :")
try:
    exec("if True\n    pass")
except SyntaxError as e:
    print(f"   实际报错：{type(e).__name__}: {e.msg}（第 {e.lineno} 行）")

# --- 3. IndentationError ---
print("\n③ IndentationError —— 缩进不对")
print("   原因：Python 靠缩进判断层级，该缩进没缩进，或乱缩")
try:
    exec("if True:\nprint('没有缩进')")
except IndentationError as e:
    print(f"   实际报错：{type(e).__name__}: {e.msg}")

# --- 4. TypeError ---
print("\n④ TypeError —— 类型不对，或者参数个数不对")
print("   原因：比如把文字和数字直接相加；或者函数要求 2 个参数你只给了 1 个")


def 需要两个参数(a, b):
    return a + b


try:
    需要两个参数(1)
except TypeError as e:
    print(f"   实际报错：{e}")

try:
    print("里程" + 100)
except TypeError as e:
    print(f"   实际报错：{e}")

# --- 5. ZeroDivisionError ---
print("\n⑤ ZeroDivisionError —— 除以 0")
print("   原因：分母是 0。在测试数据里很容易踩到。")
try:
    print(10 / 0)
except ZeroDivisionError as e:
    print(f"   实际报错：{e}")

# --- 6. FileNotFoundError ---
print("\n⑥ FileNotFoundError —— 文件找不到")
print("   原因：路径写错，或者文件不在那个位置")
try:
    open("这个文件不存在.txt", "r", encoding="utf-8")
except FileNotFoundError as e:
    print(f"   实际报错：{e}")


# ==================================================================
# 三、出错时的五步排查法
# ==================================================================
print("=" * 64)
print("【三】出错了，按这五步走")
print("=" * 64)

print("""
    第 1 步：看最后一行，搞清楚「是什么错」
             （上面的 6 种，能认出 4 种就够用了）

    第 2 步：看最后那个 File 行，找到「第几行」
             注意是【最后一个】File 行，不是最上面那个

    第 3 步：去那一行，看那一行的上一行有没有问题
             （很多错误其实出在上一行，比如上一行漏了括号）

    第 4 步：检查最常见的三个嫌疑人
             - 名字打错了吗？（大小写、拼写）
             - 冒号 `:` 漏了吗？（if / for / def 后面）
             - 缩进对吗？（该 4 个格的缩进没有）

    第 5 步：还是不行，就把报错最后一行复制去搜索
             这是程序员的日常操作，不丢人
""")


