"""
第 03 课 · 第一个函数（定义 ≠ 执行）
================================================================
这一课只讲一件事，但它是 90% 的人卡住的第一个地方：

        def   是「定义」  —— 只是登记，什么都不做
        名字() 是「调用」  —— 这才真的去执行

记住这句话，函数就学会一半了。
"""

print("=" * 64)
print("第 03 课 · 第一个函数")
print("=" * 64)


# ==================================================================
# 第一步：写一个最简单的函数
# ==================================================================
# 格式：
#     def 函数名():
#         这里写要干的活（注意缩进 4 个格）

print("\n【第一步】先把函数写出来")
print("下面这 3 行是「定义」，只是把菜谱写进本子里。\n")


def 打招呼():
    print("    你好，我是余泽泓")
    print("    我做智能驾驶测试")


print("↑ 上面这段代码已经执行过了，但你看到任何输出吗？没有。")
print("  因为 def 只是「登记」，它不会真的去跑里面的代码。")
print("  就像菜谱写在本子上，锅还是凉的。\n")

print("那怎么让它真的跑起来？加一对括号，喊它的名字。")


# ==================================================================
# 第二步：调用（喊名字）
# ==================================================================
print("\n【第二步】调用：名字后面加括号 ()\n")

打招呼()          # ← 这一行才是"真的去做"

print("\n↑ 刚才那两行输出，就是从函数里面打印出来的。\n")

print("再喊两次，它就再跑两遍：")
打招呼()
打招呼()


# ==================================================================
# 第三步：定义 和 调用 是两件不同的事
# ==================================================================
print("\n" + "=" * 64)
print("【第三步】最容易搞混的地方")
print("=" * 64)

print("""
    打招呼        <- 提到这个名字，但没加括号 = 只是"提了一句"
    打招呼()      <- 加了括号 = "去做！"

下面做个实验，你就彻底明白了。
""")

print("我们先看看「提名字」会发生什么：")
x = 打招呼            # 注意：这里故意没写括号
print(f"    x 的值是：{x}")
print("    看到没？它是一个「函数」，被装进了 x 这个名字里。")
print("    但里面那两行 print 一句都没执行。\n")

print("现在给 x 也加上括号：")
x()                   # 加了括号，就执行了
print("    ↑ 这次执行了。")

print("""
结论：
    没有括号 = 只是提到这个名字（相当于把菜谱拿在手上）
    有括号   = 真的执行（相当于照着菜谱开火炒）

这个区别在真实代码里非常重要，后面学 return 的时候还会再遇到。
""")


# ==================================================================
# 第四步：函数可以先写调用，但定义必须在调用之前
# ==================================================================
print("=" * 64)
print("【第四步】一个必须遵守的顺序")
print("=" * 64)

print("""
    定义 (def) 必须写在 调用 的前面。

为什么？因为 Python 是从上往下一行一行读的。
读到 def 的那一行，它才知道「哦，有这么个函数」。
如果你先调用了，它还没读到 def，就会报错说"找不到这个名字"。

所以规矩是：先 def，后调用。（本文件就是按这个顺序写的）
""")


