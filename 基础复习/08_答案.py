print("【第 4 题】判通过")

print("""
思路：用 if 判断，两个 return 走不同的路。

    def 判通过(error数, 上限):
        if error数 > 上限:
            return False
        return True

也可以写成一行：
    def 判通过(error数, 上限):
        return error数 <= 上限

意思完全一样，第二种更简洁。第一种更好读。
新手建议先写第一种（看得清楚），熟练了再用第二种。
""")


def 判通过(error数, 上限):
    if error数 > 上限:
        return False
    return True


