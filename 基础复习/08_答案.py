print("-" * 64)
print("【第 2 题】算总和")

print("""
思路：准备一个「篮子」（total = 0），把数字一个个捡进去。

    def 算总和(数字们):
        total = 0
        for n in 数字们:
            total = total + n
        return total

两个关键点：
    1. total = 0 必须写在 for 的外面（写在里面每次都被清零）
    2. return 必须写在 for 的外面（写在里面只返回第一个数就结束了）
""")


def 算总和(数字们):
    total = 0
    for n in 数字们:
        total = total + n
    return total


print(f"    测试：算总和([1,2,3,4]) -> {算总和([1, 2, 3, 4])}")


