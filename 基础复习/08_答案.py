print("【第 5 题】挑出错误行")

print("""
思路：建一个空列表 -> 逐行看 -> 符合条件的放进去 -> 返回。

    def 挑出错误行(日志行们):
        结果 = []
        for 行 in 日志行们:
            if "[ERROR]" in 行:
                结果.append(行)
        return 结果

三个关键点：
    1. 结果是「新建」的空列表，不要改传进来的原列表
    2. append 写在 if 里面（写在 if 外面就全放进去了）
    3. return 写在 for 外面（写在里面只会返回第一行）
""")


def 挑出错误行(日志行们):
    结果 = []
    for 行 in 日志行们:
        if "[ERROR]" in 行:
            结果.append(行)
    return 结果


