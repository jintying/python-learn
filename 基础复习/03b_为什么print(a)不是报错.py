"""
第 03b 课 · 补充：print(a) 为什么不是报错
================================================================
这是你亲手试出来的问题，非常好，因为它正好卡在函数的核心上。

你写的代码：

    def a():
        print("hello world")

    print(a)

输出是：

    <function a at 0x000001F8C3A2B4C0>

很多人第一次看到这个，都以为"报错了"。其实不是 —— 它是正确答案。
这一课就讲清楚：那串东西到底是什么。
"""

print("=" * 64)
print("第 03b 课 · print(a) 为什么不是报错")
print("=" * 64)


def a():
    print("    hello world")


# ==================================================================
# 一、先看清楚：它到底是不是报错
# ==================================================================
print("\n【一】报错长什么样 vs 你这个长什么样")

print("""
报错的样子（还记得第 06 课吗）：

    Traceback (most recent call last):
      File "test.py", line 5, in <module>
        print(a)
    NameError: name 'a' is not defined

    ↑ 有 Traceback、有 File、有 XXError。那才是报错。

你这个的样子：

    <function a at 0x000001F8C3A2B4C0>

    ↑ 没有 Traceback、没有 Error 字样。它是正常的输出结果。
""")

print("我们现在真的把它打印出来，你看一眼：\n")
print("    ", a)

print("""
看到没？没有 Traceback，没有 Error。
那就说明：程序正常跑完了，这就是它给出的答案。
""")


# ==================================================================
# 二、逐字拆解那串怪东西
# ==================================================================
print("=" * 64)
print("【二】那串东西到底在说什么？")
print("=" * 64)

print("""
    <function a at 0x000001F8C3A2B4C0>
     ────┬─── ─┬─    ───────┬───────
         │     │            │
         │     │            └─ ③ 它在内存里的地址，每次运行都不一样
         │     │                 这一串你完全不用管，忽略它就行
         │     │
         │     └─ ② 它的名字叫 a
         │
         └─ ① 它是一个「函数」（function）

连起来读就是：

        「你问我的 a 是啥？a 是一个函数，它叫 a，住在内存的这个地址。」
""")

print("我们来验证一下这三部分：\n")
print(f"    直接打印 a        ->  {a}")
print(f"    a 是什么类型      ->  {type(a)}")
print(f"    a 的名字          ->  {a.__name__}")

print("""
所以问题的根本是：

    你 print 的是「a 本身」，Python 就老老实实告诉你「a 是个函数」。

就像一个快递员，你问他"你手上那个盒子是啥？"
他会回答"这是个盒子" —— 而不是把盒子拆开给你看里面的东西。
""")


# ==================================================================
# 三、四种写法的对比（这一节是重点）
# ==================================================================
print("=" * 64)
print("【三】四种写法，四种结果 —— 一定要分清")
print("=" * 64)

print("""
我们来做 4 个实验，你盯着看它们的区别。
""")

print("-" * 64)
print("实验 1：只写 a   （不加括号，也不 print）")
print("-" * 64)
print("    代码：a")
a                       # 这一行什么都不会显示
print("    ↑ 什么都没显示。因为这只是「提了一下这个名字」，没让它干活。")

print("-" * 64)
print("实验 2：写 a()   （加了括号）")
print("-" * 64)
print("    代码：a()")
a()                     # 这一行才真的执行，打印出 hello world
print("    ↑ 这次真的执行了，输出了 hello world。")

print("-" * 64)
print("实验 3：写 print(a)   （打印函数本身）")
print("-" * 64)
print("    代码：print(a)")
print("    ", a)
print("    ↑ 打印出来的是「a 这个函数」，所以是 <function a at 0x...>。")

print("-" * 64)
print("实验 4：写 print(a())   （先调用，再把结果打印出来）")
print("-" * 64)
print("    代码：print(a())")
print("    下面是它的实际输出：")
print("    ---- 输出开始 ----")
print(a())
print("    ---- 输出结束 ----")
print("""
    ↑ 注意！这里输出了两行：
        第 1 行  hello world   <- 这是 a() 里面的 print 干的
        第 2 行  None          <- 这是外面那层 print 打印的

    为什么第 2 行是 None？
    因为 a() 这个函数里面只有 print，没有 return。
    还记得第 05 课吗 ——

        没有 return 的函数，默认返回 None。

    所以流程是：
        a() 先执行，打印出 "hello world"，然后交出一个 None
        外面那层 print 接到这个 None，把它打印出来
""")


# ==================================================================
# 四、一句话记住
# ==================================================================
print("=" * 64)
print("【四】一句话记住区别")
print("=" * 64)

print("""
        a        =  「a 这个函数」本身     （一个东西）
        a()      =  「去执行 a」           （一个动作）

    加括号 = 去干活。不加括号 = 只是在说这个东西本身。

所以：
    你想让它打印 hello world  ->  写 a()      （或 print(a())）
    你想看看 a 是什么          ->  写 print(a) （得到 <function a ...>）
""")


# ==================================================================
# 五、一个更深一点的事：函数也是一个"值"
# ==================================================================
print("=" * 64)
print("【五】顺便懂一个更深的事：函数本身也是一个「值」")
print("=" * 64)

print("""
数字、文字可以装进变量，函数也可以。

    数字  5          ->  可以装进 n，然后 print(n) 得到 5
    文字  "abc"      ->  可以装进 s，然后 print(s) 得到 abc
    函数  a          ->  可以装进 b，然后 print(b) 得到 <function a ...>

我们试一下：
""")

b = a                       # 把函数 a 装进 b 这个名字
print(f"    b = a 之后，b 是：{b}")
print(f"    b 和 a 是同一个东西吗？{b is a}")
print("    现在调用 b()：")
b()
print("    ↑ b() 和 a() 效果完全一样，因为它们指的是同一个函数。")

print("""
这说明：def a(): 这句话，本质上是
        「造了一个函数，把它装进 a 这个名字里」。

跟 n = 5（造了一个数字，装进 n）是同一回事。
这就是为什么 print(a) 能打印出东西 —— 因为 a 里装的是一个实实在在的东西。

（这个知识点现在不用深究，知道有这回事就行。
  以后学 pytest 的时候你会用到：测试函数的名字本身就是个函数对象。）
""")


