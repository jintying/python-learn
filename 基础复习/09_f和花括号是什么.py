# 四、为什么要有 f-string（对比老写法）
# ==================================================================
print("=" * 64)
print("【四】为什么要发明 f-string？看看老写法多难受")
print("=" * 64)

结果 = 30.0
车型 = "BYD海狮"

print("同一个输出，三种写法：\n")

print("写法 1：用 + 号把文字拼起来（最老最麻烦）")
print("    代码：print(\"接管率：\" + str(结果) + \" 次/千公里\")")
print("    输出：", "接管率：" + str(结果) + " 次/千公里")

print("""
    ⚠ 最烦的地方：结果是个数字，必须先用 str() 把它变成文字才能拼，
       否则会报 TypeError（文字和数字不能相加）。
       字符串一长，加号和引号就会把人搞晕。
""")

print("写法 2：用 % 占位（老式格式化，老代码里还能见到）")
print('    代码：print("接管率：%s 次/千公里" % 结果)')
print("    输出：", "接管率：%s 次/千公里" % 结果)

print("""
    ⚠ %s 和变量是分开写的，两边的顺序要自己对应，
       参数一多就很容易对错位置。
""")

print("写法 3：f-string（现在的主流，你看到的就是这个）")
print('    代码：print(f"接管率：{结果} 次/千公里")')
print("    输出：", f"接管率：{结果} 次/千公里")

print("""
    ✅ 变量直接写在它要出现的位置上，一眼就知道哪个值放哪里。
    ✅ 不用手动 str() 转换 —— f-string 会自动把任何东西变成文字。
    ✅ 想加就加，不用管顺序。

所以现在的 Python 代码基本都用 f-string。
你在别人代码里看到写法 1 和写法 2，知道是干什么的就行。
""")


