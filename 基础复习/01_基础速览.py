# ------------------------------------------------------------------
# 1. 变量 = 给数据起个名字
# ------------------------------------------------------------------
print("\n【1】变量：给数据起个名字，以后喊名字就行")

che = "红旗天工08"      # 文字（字符串），要用引号包起来
licheng = 60000        # 整数，不用引号
pingjun = 2.5          # 小数
zhengchang = True      # 真/假，只有 True 和 False 两个值，首字母必须大写

print("车型：", che)
print("累计里程：", licheng)
print("平均接管：", pingjun)
print("一切正常：", zhengchang)

# f-string：把变量塞进一句话里。前面加个 f，变量用 {} 包住。
# 这是日常最常用的写法，一定要会。
print(f"{che} 累计跑了 {licheng} 公里，平均每千公里接管 {pingjun} 次")

# 等号 = 是"赋值"，不是数学上的"相等"。
# 读作："把右边的值，装进左边这个名字里"。
a = 1
a = a + 1        # 先算右边（1+1=2），再装回 a
print("a 现在是：", a)     # 2


# ------------------------------------------------------------------
# 2. 列表 = 一排数据，用 [] 装，从 0 开始数
# ------------------------------------------------------------------
print("\n【2】列表：一排数据放在一起")

ches = ["红旗天工08", "BYD海狮", "仰望U8", "仰望U9"]

print("整个列表：", ches)
print("第 1 个（下标是 0，不是 1）：", ches[0])
print("第 2 个：", ches[1])
print("最后一个（用 -1 表示倒数第一）：", ches[-1])
print("一共几个：", len(ches))

ches.append("元戎测试车")      # 往末尾加一个
print("加了一个之后：", ches)

# for 循环：把列表里的东西一个一个拿出来
print("一个一个过一遍：")
for c in ches:
    print("    -", c)


# ------------------------------------------------------------------
# 3. 字典 = 一对一对的数据，用 {} 装，写成  键: 值
# ------------------------------------------------------------------
print("\n【3】字典：一个东西的多个属性")

baogao = {
    "车型": "BYD海狮",
    "里程": 20000,
    "ERROR": 5,
    "FAIL": 4,
}

print("整个字典：", baogao)
print('取「车型」这一项：', baogao["车型"])       # 用键取值
print("所有的键：", list(baogao.keys()))
print("所有的值：", list(baogao.values()))

baogao["WARN"] = 6              # 加一项新的
print("加了一项之后：", baogao)

print("逐行打印出来：")
for k, v in baogao.items():     # items() 一次同时拿到 键 和 值
    print(f"    {k} -> {v}")


# ------------------------------------------------------------------
# 4. if 判断 = 让程序做选择
# ------------------------------------------------------------------
print("\n【4】if：让程序做选择")

error_count = 5

if error_count > 10:
    print("ERROR 太多了，这个版本不能发")
elif error_count > 3:
    print("ERROR 有点多，需要人工看一眼")
else:
    print("ERROR 数量正常，可以发")

print("""
注意两件事：
  1. if / elif / else 每一行末尾都有冒号 :
  2. 下面的代码必须缩进（前面空 4 个格）
     在 Python 里，缩进不是"为了好看"，它是语法的一部分，
     缩进错了程序直接报错。
""")


# ------------------------------------------------------------------
# 5. 合起来用：一个小小的日志汇总
# ------------------------------------------------------------------
print("\n【5】把上面学的合起来")

logs = [
    {"车": "veh_001", "ERROR": 2, "FAIL": 1},
    {"车": "veh_002", "ERROR": 1, "FAIL": 1},
    {"车": "veh_003", "ERROR": 2, "FAIL": 2},
]

zong_error = 0
for log in logs:
    print(f"    {log['车']}：ERROR={log['ERROR']}，FAIL={log['FAIL']}")
    zong_error = zong_error + log["ERROR"]      # 累加

print(f"ERROR 总共 {zong_error} 个")

if zong_error > 10:
    print("结论：不通过")
else:
    print("结论：通过")


