def count_errors(path):
    """统计一个日志文件里含 [ERROR] 的行数。"""
    total = 0                              # ① 准备篮子
    with open(path, "r", encoding="utf-8") as f:   # ② 打开文件，用完自动关
        for line in f:                     # ③ 一行一行读（大文件不爆内存）
            if "[ERROR]" in line:          # ④ 判断这一行有没有 ERROR
                total += 1                 # ⑤ 有就 +1
    return total                           # ⑥ 交出去（不要 print！）


# 【背这个骨架】就这 6 行，换任何"数有多少个"的题都长这样
#     total = 0
#     for x in 一串东西:
#         if 条件:
#             total += 1
#     return total

