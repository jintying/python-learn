def count_by_module(lines):
    """输入日志行列表，返回 {模块名: 错误次数}。"""
    result = {}
    for line in lines:
        if "[ERROR]" not in line:
            continue                                  # 不是 ERROR 就跳过

        # "[ERROR] map_load: chunk failed" -> 取 "map_load"
        try:
            module = line.split("] ")[1].split(":")[0].strip()
        except IndexError:
            continue                                  # 格式不对就跳过，别让脚本崩

        result[module] = result.get(module, 0) + 1    # 字典计数的一行写法
    return result


# 【背这个骨架】
#     result = {}
#     for line in lines:
#         if 条件:
#             名字 = 从这行里切出来
#             result[名字] = result.get(名字, 0) + 1
#     return result
#
#   result.get(名字, 0) 的意思是：有就取出来，没有就当 0。然后 +1 再存回去。
#   这一行代替了 if/else 两个分支，是 Python 里最常用的字典计数写法。

