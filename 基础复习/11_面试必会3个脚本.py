def compare_version(a, b):
    """a 比 b 新返回 1，旧返回 -1，相同返回 0。"""
    va = [int(x) for x in a.split(".")]     # "1.2.10" -> [1, 2, 10]
    vb = [int(x) for x in b.split(".")]

    n = max(len(va), len(vb))               # 补零到一样长
    va += [0] * (n - len(va))
    vb += [0] * (n - len(vb))

    if va > vb:                             # 列表比较是逐个比，正好能用
        return 1
    if va < vb:
        return -1
    return 0


def is_newer(a, b):
    """判断 a 是否比 b 新 —— OTA 里防降级就用这个。"""
    return compare_version(a, b) > 0


# 【背这个骨架】
#     va = [int(x) for x in a.split(".")]
#     vb = [int(x) for x in b.split(".")]
#     两边补 0 到等长
#     比元组/列表

print("    测试结果：")
