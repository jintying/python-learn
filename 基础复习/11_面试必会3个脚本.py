def smoke_gate(lines, error_limit=5):
    """返回 (能不能发, 说明)。这就是发版守门最小的样子。"""
    total = sum(1 for line in lines if "[ERROR]" in line)     # 复用脚本1的思路

    if total > error_limit:
        return False, f"不通过：ERROR {total} 条，超过上限 {error_limit}"
    return True, f"通过：ERROR {total} 条，未超过上限 {error_limit}"


